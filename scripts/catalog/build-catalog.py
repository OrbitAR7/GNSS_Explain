"""Generates src/gnss/catalogData.ts from the researched constellation tables.

Input: the researched tables {system: {satellites: [...]}} and overrides.json
(verified corrections and the user-facing note for each satellite).
Usage: python3 build-catalog.py tables.json overrides.json ../../src/gnss/catalogData.ts YYYY-MM-DD
"""
import json
import re
import sys

SYSTEM_IDS = {'GPS': 'GPS', 'Galileo': 'GAL', 'GLONASS': 'GLO'}


def system_id(name):
    for k, v in SYSTEM_IDS.items():
        if name.startswith(k):
            return v
    return 'BDS'


def clean_block(block, sid):
    block = re.sub(r'\s*\(.*\)$', '', block or '').strip()
    if sid == 'GPS' and block:
        return f'Block {block}'
    if block == 'BDS-3S':
        return 'BDS-3S (experimental)'
    return block


def clean_signals(signals, status):
    if status == 'decommissioned' or not signals or signals.startswith(('none', 'unknown')):
        return ''
    return re.sub(r'\s*\(.*\)$', '', signals).strip()


def main(tables_path, overrides_path, out_path, as_of):
    tables = json.load(open(tables_path))
    overrides = json.load(open(overrides_path))
    by_norad = {}
    for name, table in tables.items():
        sid = system_id(name)
        for s in table['satellites']:
            by_norad[s['norad']] = {
                'norad': s['norad'],
                'system': sid,
                'prn': s['prn'] or '',
                'svn': s.get('svn') or '',
                'block': clean_block(s.get('block'), sid),
                'orbit': s['orbit'],
                'plane': s.get('plane') or '',
                'slot': s.get('slot') or '',
                'freqChannel': s.get('freqChannel') or 0,
                'status': s['status'],
                'signals': clean_signals(s.get('signalsOpenL1Band'), s['status']),
                'notes': '',
            }
    applied = 0
    for norad, fields in overrides['corrections'].items():
        by_norad[int(norad)].update(fields)
        applied += 1
    for entry in by_norad.values():
        note = overrides['notes'].get(str(entry['norad']))
        if note is None and entry['status'] == 'decommissioned' and entry['block'].startswith('BDS-2'):
            note = overrides['retiredNote']
        entry['notes'] = note or ''
    entries = sorted(by_norad.values(), key=lambda e: (e['system'], e['prn'] or 'zz', e['norad']))
    lines = [
        '// Generated by scripts/catalog/build-catalog.py — do not edit by hand.',
        f'// Satellite catalogue as of {as_of}: PRN/SVID, block, orbit, plane/slot, GLONASS',
        '// frequency channel and service status, keyed by NORAD catalogue number. Sources:',
        '// operator status pages and notices (USCG NAVCEN / NANU, GSC NAGU, IAC, CSNO-TARC),',
        '// IGS MGEX metadata and the Cabinet Office (QZSS) GNSS satellite list.',
        '//',
        *[f'// {sid}: {text}' for sid, text in overrides.get('_verification', {}).items()],
        "import type { SatelliteInfo } from './catalog';",
        '',
        f"export const CATALOG_AS_OF = '{as_of}';",
        '',
        'export const CATALOG_ENTRIES: SatelliteInfo[] = [',
    ]
    for e in entries:
        lines.append('  ' + json.dumps(e, ensure_ascii=False) + ',')
    lines.append('];')
    open(out_path, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(entries)} entries, {applied} corrections applied')


if __name__ == '__main__':
    main(*sys.argv[1:5])
